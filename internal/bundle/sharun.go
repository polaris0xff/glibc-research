// sharun.go — sharun as AppRun, the hardlinks it dispatches on, and the
// environment the bundle carries.
//
// The hardlink is the mechanism, not a shortcut: sharun looks at the name it
// was invoked as and runs shared/bin/<that name>, which is how /proc/self/exe
// ends up naming the application rather than the loader. The hardlinks go at
// the TOP level, because sharun takes its AppDir from its own location — one
// under bin/ makes it treat bin/ as the root, where there is no .env and no
// lib, and a Qt application then aborts with no output at all.
//
// SPDX-License-Identifier: MIT
package bundle

